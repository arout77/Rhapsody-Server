    public static string MyIni(string baseDir, string dataDir, int port) => $"""
        [mysqld]
        basedir={F(baseDir)}
        datadir={F(dataDir)}
        port={port}
        bind-address=127.0.0.1
        skip-name-resolve
        character-set-server=utf8mb4
        collation-server=utf8mb4_unicode_ci
        max_allowed_packet=64M
        innodb_buffer_pool_size=128M
        innodb_flush_log_at_trx_commit=2
        [client]
        port={port}
        default-character-set=utf8mb4
        """;

    public static string RedisConf(string dataDir, int port) => $"""
        bind 127.0.0.1
        port {port}
        save ""
        appendonly no
        dir {F(dataDir)}
        """;

