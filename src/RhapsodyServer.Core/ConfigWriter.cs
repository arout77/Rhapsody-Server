    // ------------------------------------------------------------------ nginx
    public static string Nginx(Settings s, IReadOnlyList<SiteSpec> sites, string nginxDir, string prefix, string fastcgiFile, bool profiling = false)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Rhapsody Server. Manual edits are overwritten.");
        sb.AppendLine("worker_processes 1;");
        sb.AppendLine($"error_log \"{F(prefix)}/logs/error.log\" warn;");
        sb.AppendLine($"pid \"{F(prefix)}/logs/nginx.pid\";");
        sb.AppendLine("events { worker_connections 1024; }");
        sb.AppendLine("http {");
        sb.AppendLine($"    include \"{F(nginxDir)}/conf/mime.types\";");
        sb.AppendLine("    default_type application/octet-stream;");
        if (profiling)
        {
            sb.AppendLine("    " + RhapsodyServer.Core.Profiling.AccessLogTailer.LogFormatNginx);
            sb.AppendLine($"    access_log \"{F(prefix)}/logs/profile.tsv\" rs_profile;");
        }
        else sb.AppendLine("    access_log off;");
        sb.AppendLine("    client_max_body_size 128m;");
        sb.AppendLine("    server_names_hash_bucket_size 128;");
        sb.AppendLine("    fastcgi_read_timeout 300s;");
        sb.AppendLine("    fastcgi_buffer_size 32k;");
        sb.AppendLine("    fastcgi_buffers 16 16k;");
        sb.AppendLine("    map $http_upgrade $connection_upgrade { default upgrade; '' close; }");

        foreach (var branch in sites.Where(x => x.DocRoot != null).Select(x => x.Php).Distinct())
        {
            sb.AppendLine($"    upstream {Up(branch)} {{");
            foreach (var port in PhpPorts.Ports(branch, s.PhpWorkersPerVersion))
                sb.AppendLine($"        server 127.0.0.1:{port};");
            sb.AppendLine("    }");
        }

        foreach (var site in sites)
        {
            sb.AppendLine("    server {");
            sb.AppendLine($"        listen 127.0.0.1:{s.HttpPort};");
            if (site.Https)
            {
                sb.AppendLine($"        listen 127.0.0.1:{s.HttpsPort} ssl;");
                sb.AppendLine("        http2 on;");
                sb.AppendLine($"        ssl_certificate \"{F(site.CertFile)}\";");
                sb.AppendLine($"        ssl_certificate_key \"{F(site.KeyFile)}\";");
            }
            sb.AppendLine($"        server_name {site.Domain};");

            if (site.ProxyTo != null)
            {
                sb.AppendLine("        location / {");
                sb.AppendLine($"            proxy_pass http://{site.ProxyTo};");
                sb.AppendLine("            proxy_http_version 1.1;");
                sb.AppendLine("            proxy_set_header Host $host;");
                sb.AppendLine("            proxy_set_header Upgrade $http_upgrade;");
                sb.AppendLine("            proxy_set_header Connection $connection_upgrade;");
                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        root \"{F(site.DocRoot!)}\";");
                sb.AppendLine("        index index.php index.html;");
                sb.AppendLine("        location / { try_files $uri $uri/ /index.php?$query_string; }");
                sb.AppendLine("        location ~ \\.php$ {");
                sb.AppendLine($"            include \"{F(fastcgiFile)}\";");
                sb.AppendLine($"            fastcgi_pass {Up(site.Php)};");
                sb.AppendLine("        }");
                sb.AppendLine("        location ~ /\\.(?!well-known) { deny all; }");
            }
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    // ----------------------------------------------------------------- apache
    /// <param name="optionalModules">Modules to load on top of the ones Rhapsody Server's config needs. Null = the defaults.</param>
    public static string Apache(Settings s, IReadOnlyList<SiteSpec> sites, string apacheDir, string prefix, bool profiling = false,
        IReadOnlyCollection<string>? optionalModules = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Rhapsody Server. Manual edits are overwritten.");
        sb.AppendLine($"ServerRoot \"{F(apacheDir)}\"");
        sb.AppendLine("ServerName localhost");
        sb.AppendLine($"PidFile \"{F(prefix)}/logs/httpd.pid\"");
        sb.AppendLine($"ErrorLog \"{F(prefix)}/logs/error.log\"");
        sb.AppendLine("LogLevel warn");
        if (profiling)
        {
            sb.AppendLine(RhapsodyServer.Core.Profiling.AccessLogTailer.LogFormatApache);
            sb.AppendLine($"CustomLog \"{F(prefix)}/logs/profile.tsv\" rs_profile");
        }
        sb.AppendLine($"Listen 127.0.0.1:{s.HttpPort}");
        sb.AppendLine($"Listen 127.0.0.1:{s.HttpsPort}");
        foreach (var m in ApacheModuleCatalog.Required)
            sb.AppendLine(ApacheModuleCatalog.LoadLine(m));
        foreach (var m in ApacheModuleCatalog.Optional(optionalModules ?? ApacheModuleCatalog.Defaults, null))
            sb.AppendLine(ApacheModuleCatalog.LoadLine(m));

        sb.AppendLine($"TypesConfig \"{F(apacheDir)}/conf/mime.types\"");
        sb.AppendLine("DirectoryIndex index.php index.html");
        sb.AppendLine("<Directory />\n    AllowOverride None\n    Require all denied\n</Directory>");
        // Sites can be served from the project root (Rhapsody does), so .env, .htaccess, .git and friends sit inside the web root.
        // Never serve them. (.well-known stays reachable.)
        sb.AppendLine("<FilesMatch \"^\\.\">\n    Require all denied\n</FilesMatch>");
        sb.AppendLine("<DirectoryMatch \"/\\.(?!well-known)\">\n    Require all denied\n</DirectoryMatch>");
        sb.AppendLine($"SSLSessionCache \"shmcb:{F(prefix)}/logs/ssl_scache(512000)\"");

        var multi = s.PhpWorkersPerVersion > 1;
        if (multi)
            foreach (var branch in sites.Where(x => x.DocRoot != null).Select(x => x.Php).Distinct())
            {
                sb.AppendLine($"<Proxy \"balancer://{Up(branch)}\">");
                foreach (var port in PhpPorts.Ports(branch, s.PhpWorkersPerVersion))
                    sb.AppendLine($"    BalancerMember \"fcgi://127.0.0.1:{port}\"");
                sb.AppendLine("</Proxy>");
            }

        foreach (var site in sites)
        {
            void Body(StringBuilder b)
            {
                b.AppendLine($"    ServerName {site.Domain}");
                if (site.ProxyTo != null)
                {
                    b.AppendLine("    ProxyPreserveHost On");
                    b.AppendLine($"    ProxyPass \"/api/events\" \"ws://{site.ProxyTo}/api/events\"");
                    b.AppendLine($"    ProxyPass \"/\" \"http://{site.ProxyTo}/\"");
                    b.AppendLine($"    ProxyPassReverse \"/\" \"http://{site.ProxyTo}/\"");
                    return;
                }
                var doc = F(site.DocRoot!);
                var target = multi
                    ? $"balancer://{Up(site.Php)}"
                    : $"fcgi://127.0.0.1:{PhpPorts.BasePort(site.Php)}";
                b.AppendLine($"    DocumentRoot \"{doc}\"");
                b.AppendLine($"    <Directory \"{doc}\">");
                b.AppendLine("        Options FollowSymLinks");
                b.AppendLine("        AllowOverride All");
                b.AppendLine("        Require all granted");
                b.AppendLine("        FallbackResource /index.php");
                b.AppendLine("    </Directory>");
                b.AppendLine("    <FilesMatch \"\\.php$\">");
                b.AppendLine($"        SetHandler \"proxy:{target}\"");
                b.AppendLine("    </FilesMatch>");
            }

            sb.AppendLine($"<VirtualHost 127.0.0.1:{s.HttpPort}>");
            Body(sb);
            sb.AppendLine("</VirtualHost>");
            if (site.Https)
            {
                sb.AppendLine($"<VirtualHost 127.0.0.1:{s.HttpsPort}>");
                sb.AppendLine("    SSLEngine on");
                sb.AppendLine($"    SSLCertificateFile \"{F(site.CertFile)}\"");
                sb.AppendLine($"    SSLCertificateKeyFile \"{F(site.KeyFile)}\"");
                Body(sb);
                sb.AppendLine("</VirtualHost>");
            }
        }
        return sb.ToString();
    }

    // -------------------------------------------------------------------- php
    /// <param name="o">Which extensions are on and how OPcache is provided. Null = the defaults for this PHP version.</param>
    public static string PhpIni(string branch, string phpDir, string tmpDir, Settings s, PhpIniOptions? o = null)
    {
        o ??= PhpIniOptions.Default(branch);
        string Ext(string n)
        {
            if (branch == "7.1") return $"extension=php_{(n == "gd" ? "gd2" : n)}.dll"; // 7.1 uses prefixed dll names
            return $"extension={n}";
        }

        var exts = o.Extensions.Where(e => e != "opcache").OrderBy(e => e, StringComparer.Ordinal).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("; Generated by Rhapsody Server. Manual edits are overwritten.");
        sb.AppendLine("[PHP]");
        sb.AppendLine("engine=On");
        sb.AppendLine("short_open_tag=Off");
        sb.AppendLine("memory_limit=512M");
        sb.AppendLine("max_execution_time=120");
        sb.AppendLine("max_input_vars=5000");
        sb.AppendLine("error_reporting=E_ALL");
        sb.AppendLine("display_errors=On");
        sb.AppendLine("log_errors=On");
        sb.AppendLine($"error_log=\"{Util.Fwd(tmpDir)}/php_error.log\"");
        sb.AppendLine("file_uploads=On");
        sb.AppendLine("upload_max_filesize=128M");
        sb.AppendLine("post_max_size=128M");
        sb.AppendLine($"upload_tmp_dir=\"{Util.Fwd(tmpDir)}\"");
        sb.AppendLine("allow_url_fopen=On");
        sb.AppendLine("cgi.fix_pathinfo=1");
        sb.AppendLine("cgi.force_redirect=0");
        sb.AppendLine("realpath_cache_size=4096K");   // big win on Windows: path lookups are slow
        sb.AppendLine("realpath_cache_ttl=600");
        sb.AppendLine($"extension_dir=\"{Util.Fwd(phpDir)}/ext\"");
        foreach (var e in exts) sb.AppendLine(Ext(e));
        // PHP 8.5 compiled OPcache into PHP itself: there is no opcache DLL to load, and asking for one is the
        // "Failed loading Zend extension 'opcache'" warning. Only load the module when the file is really there.
        if (o.LoadOpcacheModule) sb.AppendLine(branch == "7.1" ? "zend_extension=php_opcache.dll" : "zend_extension=opcache");
        sb.AppendLine("[Date]");
        sb.AppendLine($"date.timezone={s.Timezone}");
        sb.AppendLine("[mail function]");
        sb.AppendLine("SMTP=127.0.0.1");
        sb.AppendLine($"smtp_port={s.SmtpPort}");
        sb.AppendLine("sendmail_from=dev@localhost");
        sb.AppendLine("[opcache]");
        sb.AppendLine(o.OpcacheEnabled ? "opcache.enable=1" : "opcache.enable=0");
        sb.AppendLine("opcache.enable_cli=0");
        sb.AppendLine("opcache.memory_consumption=128");
        sb.AppendLine("opcache.interned_strings_buffer=16");
        sb.AppendLine("opcache.max_accelerated_files=20000");
        sb.AppendLine("opcache.validate_timestamps=1");
        sb.AppendLine("opcache.revalidate_freq=1");
        sb.AppendLine("[Session]");
        sb.AppendLine($"session.save_path=\"{Util.Fwd(tmpDir)}/sessions\"");
        return sb.ToString();
    }

