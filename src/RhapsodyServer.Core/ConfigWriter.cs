/// <param name="DocRoot">PHP site document root, or null for a proxied site.</param>
/// <param name="ProxyTo">host:port to reverse-proxy to (Mailpit UI), or null.</param>
public sealed record SiteSpec(string Domain, string? DocRoot, string? ProxyTo, string Php, bool Https, string CertFile, string KeyFile);

public static class PhpPorts
{
    /// <summary>9000 + major*100 + minor*10: PHP 8.4 workers sit on 9840, 9841...  Readable in netstat.</summary>
    public static int BasePort(string branch)
    {
        var p = branch.Split('.');
        return 9000 + int.Parse(p[0]) * 100 + int.Parse(p[1]) * 10;
    }

    public static IEnumerable<int> Ports(string branch, int workers) =>
        Enumerable.Range(BasePort(branch), Math.Clamp(workers, 1, 10));
}

/// <param name="Extensions">Names of the extensions to switch on ("gd", "mbstring"...). May include "opcache".</param>
/// <param name="LoadOpcacheModule">Emit zend_extension for OPcache. False when it is built into PHP (8.5+).</param>
/// <param name="OpcacheEnabled">Whether OPcache should run.</param>
public sealed record PhpIniOptions(IReadOnlyList<string> Extensions, bool LoadOpcacheModule, bool OpcacheEnabled = true)
{
    /// <summary>The defaults for a PHP version, without looking at the disk: OPcache is a DLL up to 8.4, built in from 8.5.</summary>
    public static PhpIniOptions Default(string branch) =>
        new(PhpExtensions.Defaults(branch), !PhpExtensions.OpcacheIsBuiltIn(branch));
}

